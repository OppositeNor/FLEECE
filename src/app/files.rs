//! Host-managed file transfers for browsers and other filesystem-free embedders.
//! Downloads are acknowledged by the host before saved state or pending actions
//! advance. Imported documents use the same unsaved-change flow as native opens.
use super::*;
use serde::{Deserialize, Serialize};

/// A file operation for an embedding host to handle outside the editor.
pub enum FileRequest {
    /// Ask the user to choose a TOML document, then call [`Editor::import_document`].
    OpenDocument,
    /// Ask the user to choose a TOML palette, then call [`Editor::import_theme`].
    OpenTheme,
    /// Offer generated bytes for download, then call [`Editor::finish_download`].
    Download {
        /// Transfer identifier, echoed when the host acknowledges the request.
        id: u64,
        /// Suggested file name, without a directory.
        name: String,
        /// MIME type for the download.
        mime: &'static str,
        /// Complete validated document or encoded image.
        bytes: Vec<u8>,
    },
}

#[derive(Default)]
pub(super) struct ExternalFiles {
    requests: Vec<FileRequest>,
    next_id: u64,
    pending: Option<Download>,
    pub(super) custom_theme: Option<String>,
}
struct Download {
    id: u64,
    name: String,
    snapshot: Option<Circuit>,
    options: ExportOptions,
}
#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Settings {
    theme: String,
    custom_theme: Option<String>,
    export_options: ExportOptions,
    save_name: Option<String>,
    export_name: Option<String>,
}

fn file_name(name: &str) -> Result<String, String> {
    let name = name.trim();
    if name.is_empty()
        || name.len() > 255
        || name.contains(['/', '\\'])
        || name.chars().any(char::is_control)
    {
        return Err("Choose a file name without folders or control characters.".into());
    }
    Ok(name.into())
}

impl Editor {
    /// Create an editor whose file operations are delegated to an embedding host.
    /// No native preferences, directories or filesystem dialogs are accessed.
    /// The host drains [`Self::take_file_requests`] after each frame.
    pub fn with_external_files(document: Document) -> Self {
        let mut editor = Self::new(document, None);
        editor.external_files = Some(ExternalFiles::default());
        let reference = editor.theme_reference();
        editor.remembered_theme = Some(if theme::builtin_source(&reference).is_some() {
            reference
        } else {
            "original-dark".into()
        });
        editor.apply_remembered_theme();
        editor
    }

    /// Drain pending file operations. Native editors return an empty list.
    pub fn take_file_requests(&mut self) -> Vec<FileRequest> {
        self.external_files
            .as_mut()
            .map(|files| std::mem::take(&mut files.requests))
            .unwrap_or_default()
    }

    /// Validate uploaded TOML before requesting document replacement.
    /// Unsaved changes still require the regular Save/Discard/Cancel decision.
    ///
    /// # Errors
    /// Fails without replacing the diagram for invalid names, input over 8 MiB,
    /// malformed/invalid documents, or an editor not using host-managed files.
    pub fn import_document(&mut self, name: &str, text: &str) -> Result<(), String> {
        if self.external_files.is_none() {
            return Err("This editor uses native files.".into());
        }
        let name = file_name(name)?;
        if text.len() > 8 * 1024 * 1024 {
            return Err("Document exceeds 8 MiB.".into());
        }
        let document = Document::from_toml(text)?;
        self.request(Pending::Import {
            document: Box::new(document),
            name,
        });
        Ok(())
    }

    /// Validate and activate an uploaded palette without reading a filesystem.
    /// Its source can be persisted using [`Self::external_settings`].
    ///
    /// # Errors
    /// Fails without changing the active palette for invalid/oversized themes or
    /// when the editor is not configured for host-managed files.
    pub fn import_theme(&mut self, text: &str) -> Result<(), String> {
        if self.external_files.is_none() {
            return Err("This editor uses native files.".into());
        }
        if text.len() > 256 * 1024 {
            return Err("Theme file exceeds 256 KiB.".into());
        }
        let theme = Theme::from_toml(text)?;
        self.external_files.as_mut().unwrap().custom_theme = Some(text.into());
        self.theme = theme;
        self.theme_key = "browser-custom".into();
        self.document.editor.theme = Some(self.theme_key.clone());
        self.remembered_theme = Some(self.theme_key.clone());
        self.status = format!("UI theme: {}", self.theme.name);
        Ok(())
    }

    /// Report a host file, clipboard or storage error in the editor status bar.
    pub fn report_host_error(&mut self, error: &str) {
        self.status = error.into();
    }

    /// Acknowledge a download handoff. Only success updates saved snapshots,
    /// remembered names/options and any pending unsaved-change action.
    /// Unknown or stale identifiers are ignored.
    /// A browser acknowledgement means download initiation, not confirmation that
    /// the user kept the file in the browser's download manager.
    pub fn finish_download(&mut self, id: u64, result: Result<(), String>) {
        let Some(files) = &mut self.external_files else {
            return;
        };
        if files
            .pending
            .as_ref()
            .is_none_or(|pending| pending.id != id)
        {
            return;
        }
        let pending = files.pending.take().unwrap();
        if let Err(error) = result {
            self.status = format!("Download failed: {error}");
            return;
        }
        if let Some(snapshot) = pending.snapshot {
            self.saved = snapshot;
            self.path = Some(PathBuf::from(&pending.name));
            self.preferences.last_save_path = self.path.clone();
            self.status = format!("Downloaded {}", pending.name);
            if !self.dirty() {
                self.after_save();
            }
        } else {
            self.preferences.last_export_path = Some(PathBuf::from(&pending.name));
            self.preferences.export_options = pending.options;
            self.status = format!("Exported {}", pending.name);
        }
    }

    /// Serialize browser/embedding preferences as TOML, excluding diagram content.
    ///
    /// # Errors
    /// Returns an error for native editors or serialization failure.
    pub fn external_settings(&self) -> Result<String, String> {
        let files = self
            .external_files
            .as_ref()
            .ok_or("This editor uses native files.")?;
        toml::to_string(&Settings {
            theme: self
                .remembered_theme
                .clone()
                .unwrap_or_else(|| self.theme_reference()),
            custom_theme: files.custom_theme.clone(),
            export_options: self.preferences.export_options,
            save_name: self
                .preferences
                .last_save_path
                .as_ref()
                .map(|p| p.to_string_lossy().into_owned()),
            export_name: self
                .preferences
                .last_export_path
                .as_ref()
                .map(|p| p.to_string_lossy().into_owned()),
        })
        .map_err(|e| e.to_string())
    }

    /// Restore validated browser preferences without accessing native locations.
    ///
    /// # Errors
    /// Returns an error without changing preferences for invalid settings/theme,
    /// input over 300 KiB, or an editor not using host-managed files.
    pub fn restore_external_settings(&mut self, text: &str) -> Result<(), String> {
        if self.external_files.is_none() {
            return Err("This editor uses native files.".into());
        }
        if text.len() > 300 * 1024 {
            return Err("Browser preferences exceed 300 KiB.".into());
        }
        let settings: Settings = toml::from_str(text).map_err(|e| e.to_string())?;
        let options = settings.export_options;
        if !(1..=6).contains(&options.scale)
            || !options.padding.is_finite()
            || !(0.0..=200.0).contains(&options.padding)
        {
            return Err("Invalid browser export settings.".into());
        }
        for name in [&settings.save_name, &settings.export_name]
            .into_iter()
            .flatten()
        {
            file_name(name)?;
        }
        let source = if settings.theme == "browser-custom" {
            settings
                .custom_theme
                .as_deref()
                .ok_or("Missing custom browser palette.")?
        } else {
            theme::builtin_source(&settings.theme).ok_or("Unknown browser palette.")?
        };
        if source.len() > 256 * 1024 {
            return Err("Theme file exceeds 256 KiB.".into());
        }
        let theme = Theme::from_toml(source)?;
        self.theme = theme;
        self.theme_key = settings.theme;
        self.remembered_theme = Some(self.theme_key.clone());
        self.document.editor.theme = Some(self.theme_key.clone());
        self.external_files.as_mut().unwrap().custom_theme = settings.custom_theme;
        self.export_options = options;
        self.preferences.export_options = options;
        self.preferences.last_save_path = settings.save_name.map(PathBuf::from);
        self.preferences.last_export_path = settings.export_name.map(PathBuf::from);
        Ok(())
    }

    pub(super) fn save_external(&mut self) {
        self.finish_edit();
        self.finish_drag();
        if let Some(name) = self
            .path
            .as_ref()
            .and_then(|p| p.file_name())
            .map(|n| n.to_string_lossy().into_owned())
        {
            if let Err(error) = self.queue_download(&name, true) {
                self.report_host_error(&error);
            }
        } else {
            self.file_dialog = Some(self.save_dialog());
        }
    }

    fn queue_download(&mut self, name: &str, document: bool) -> Result<(), String> {
        self.finish_edit();
        self.finish_drag();
        let name = file_name(name)?;
        let extension = PathBuf::from(&name)
            .extension()
            .map(|s| s.to_string_lossy().to_ascii_lowercase())
            .unwrap_or_default();
        let (bytes, mime, snapshot) = if document {
            if extension != "toml" {
                return Err("Use a .toml extension for diagram files.".into());
            }
            let mut portable = self.document.clone();
            if portable.editor.theme.as_deref() == Some("browser-custom") {
                portable.editor.theme = None;
            }
            (
                portable.to_toml()?.into_bytes(),
                "application/toml",
                Some(self.circuit().clone()),
            )
        } else {
            let bytes = export::encode(
                self.circuit(),
                std::path::Path::new(&name),
                self.export_options,
            )?;
            (
                bytes,
                if extension == "svg" {
                    "image/svg+xml"
                } else {
                    "image/png"
                },
                None,
            )
        };
        let files = self.external_files.as_mut().unwrap();
        if files.pending.is_some() {
            return Err("A download is already being prepared.".into());
        }
        files.next_id += 1;
        files.pending = Some(Download {
            id: files.next_id,
            name: name.clone(),
            snapshot,
            options: self.export_options,
        });
        files.requests.push(FileRequest::Download {
            id: files.next_id,
            name,
            mime,
            bytes,
        });
        Ok(())
    }

    pub(super) fn external_file_modal(&mut self, ctx: &egui::Context) {
        let Some(mut dialog) = self.file_dialog.take() else {
            return;
        };
        if matches!(dialog.mode, FileMode::Open | FileMode::Theme) {
            self.external_files
                .as_mut()
                .unwrap()
                .requests
                .push(if dialog.mode == FileMode::Open {
                    FileRequest::OpenDocument
                } else {
                    FileRequest::OpenTheme
                });
            return;
        }
        let mut submit = false;
        let mut cancel = false;
        egui::Modal::new(egui::Id::unique("file_dialog")).show(ctx, |ui| {
            ui.set_width(490.0);
            ui.heading(if dialog.mode == FileMode::Save {
                "Download document"
            } else {
                "Export image"
            });
            ui.label("File name");
            let edit = ui.text_edit_singleline(&mut dialog.name);
            if dialog.focus_name {
                edit.request_focus();
                dialog.focus_name = false;
            }
            submit = edit.lost_focus() && ctx.input(|input| input.key_pressed(Key::Enter));
            if dialog.mode == FileMode::Export {
                self.export_settings(ui);
            }
            if !dialog.error.is_empty() {
                ui.colored_label(self.theme.ui.error.egui(), &dialog.error);
            }
            ui.horizontal(|ui| {
                submit |= ui.button("Download").clicked();
                cancel = ui.button("Cancel").clicked()
                    || ctx.input(|input| input.key_pressed(Key::Escape));
            });
        });
        if cancel {
            return;
        }
        if submit {
            match self.queue_download(&dialog.name, dialog.mode == FileMode::Save) {
                Ok(()) => return,
                Err(error) => dialog.error = error,
            }
        }
        self.file_dialog = Some(dialog);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn editor() -> Editor {
        Editor::with_external_files(Document::new(Circuit::half_adder()))
    }
    fn download(editor: &mut Editor) -> (u64, Vec<u8>) {
        let requests = editor.take_file_requests();
        assert_eq!(requests.len(), 1);
        match requests.into_iter().next().unwrap() {
            FileRequest::Download { id, bytes, .. } => (id, bytes),
            _ => panic!("Expected a download"),
        }
    }

    #[test]
    fn imported_documents_are_validated_and_confirmed_before_replacement() {
        let mut editor = editor();
        let before = editor.document.clone();
        assert!(editor.import_document("bad.toml", "invalid").is_err());
        assert!(
            editor
                .import_document("../escape.toml", &before.to_toml().unwrap())
                .is_err()
        );
        assert_eq!(editor.document, before);
        editor.document.circuit.title = "Unsaved work".into();
        let replacement = Document::new(Circuit::new_fsm());
        editor
            .import_document("machine.toml", &replacement.to_toml().unwrap())
            .unwrap();
        assert!(editor.confirm_unsaved);
        assert_eq!(editor.circuit().title, "Unsaved work");
        editor.queue_download("original.toml", true).unwrap();
        let (id, bytes) = download(&mut editor);
        assert_eq!(
            Document::from_toml(std::str::from_utf8(&bytes).unwrap())
                .unwrap()
                .circuit
                .title,
            "Unsaved work"
        );
        editor.finish_download(id, Ok(()));
        assert_eq!(editor.circuit(), &replacement.circuit);
        assert_eq!(
            editor.path.as_deref(),
            Some(std::path::Path::new("machine.toml"))
        );
        assert!(!editor.dirty());
        assert!(!editor.confirm_unsaved);
    }

    #[test]
    fn downloads_only_acknowledge_the_snapshot_that_was_sent() {
        let mut editor = editor();
        editor.document.circuit.title = "First edit".into();
        editor.queue_download("first.toml", true).unwrap();
        let (id, _) = download(&mut editor);
        editor.finish_download(id + 1, Ok(()));
        assert!(editor.dirty());
        editor.finish_download(id, Err("Download blocked".into()));
        assert!(editor.dirty());
        assert!(editor.path.is_none());
        editor.queue_download("first.toml", true).unwrap();
        let (id, bytes) = download(&mut editor);
        editor.document.circuit.title = "Newer edit".into();
        editor.finish_download(id, Ok(()));
        assert!(editor.dirty());
        assert_eq!(editor.saved.title, "First edit");
        assert_eq!(
            Document::from_toml(std::str::from_utf8(&bytes).unwrap())
                .unwrap()
                .circuit
                .title,
            "First edit"
        );
    }

    #[test]
    fn exported_bytes_match_native_rendering_and_do_not_mark_the_document_saved() {
        for fsm in [false, true] {
            let mut editor = editor();
            if fsm {
                editor.document =
                    Document::from_toml(include_str!("../../examples/fsm.toml")).unwrap();
            }
            editor.document.circuit.title = "Unsaved diagram".into();
            for extension in ["png", "svg"] {
                let name = format!("image.{extension}");
                editor.queue_download(&name, false).unwrap();
                let (id, bytes) = download(&mut editor);
                assert_eq!(
                    bytes,
                    export::encode(
                        editor.circuit(),
                        std::path::Path::new(&name),
                        editor.export_options
                    )
                    .unwrap()
                );
                editor.finish_download(id, Ok(()));
                assert!(editor.dirty());
                assert_eq!(
                    editor.preferences.last_export_path,
                    Some(PathBuf::from(name))
                );
            }
            assert!(editor.queue_download("bad.gif", false).is_err());
            assert!(editor.take_file_requests().is_empty());
        }
    }

    #[test]
    fn custom_browser_themes_and_preferences_survive_new_documents_and_restart() {
        let mut editor = editor();
        let custom = "theme_version = 1\nname = 'Browser palette'\nbase = 'dark'\n[canvas]\ngate_fill = '#102030'\n";
        editor.import_theme(custom).unwrap();
        editor.queue_download("portable.toml", true).unwrap();
        let (id, bytes) = download(&mut editor);
        let portable = Document::from_toml(std::str::from_utf8(&bytes).unwrap()).unwrap();
        assert!(portable.editor.theme.is_none());
        editor.finish_download(id, Ok(()));
        let settings = editor.external_settings().unwrap();
        editor.new_fsm();
        assert_eq!(editor.active_theme().name, "Browser palette");
        let mut reopened = Editor::with_external_files(Document::new(Circuit::empty()));
        reopened.restore_external_settings(&settings).unwrap();
        assert_eq!(reopened.active_theme(), editor.active_theme());
        assert_eq!(
            reopened.preferences.last_save_path,
            Some("portable.toml".into())
        );
        assert!(
            reopened
                .restore_external_settings(&settings.replace("scale = 3", "scale = 99"))
                .is_err()
        );
        assert_eq!(reopened.active_theme().name, "Browser palette");
        reopened.select_theme("original-light").unwrap();
        let changed = reopened.external_settings().unwrap();
        assert!(!changed.contains("Browser palette"));
    }
}
